// One-off migration of the old .NET/MySQL backend into Supabase.
//
//   node scripts/migrate-from-mysql.mjs <backup.sql> <wwwroot-dir> [--upload]
//
// Writes:
//   supabase/seed.sql          game content (allow-listed real rows only, original ids kept)
//   scripts/out/feedback.sql   player feedback - personal data, git-ignored, run by hand
// With --upload (needs SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY) the referenced images
// are uploaded from <wwwroot-dir> into the public `images` bucket.

import fs from 'node:fs';
import path from 'node:path';

const [dumpPath, wwwroot] = process.argv.slice(2);
const upload = process.argv.includes('--upload');
if (!dumpPath || !wwwroot) {
	console.error('usage: node scripts/migrate-from-mysql.mjs <backup.sql> <wwwroot-dir> [--upload]');
	process.exit(1);
}

// ---------------------------------------------------------------- dump parsing

const dump = fs.readFileSync(dumpPath, 'utf8');

function columnsOf(table) {
	const m = dump.match(new RegExp('CREATE TABLE `' + table + '` \\(\\n([\\s\\S]*?)\\n\\) ENGINE'));
	if (!m) throw new Error(`no CREATE TABLE for ${table}`);
	return m[1]
		.split('\n')
		.map((l) => l.match(/^\s+`(\w+)`/))
		.filter(Boolean)
		.map((m) => m[1]);
}

// Parses the tuples of `INSERT INTO `table` VALUES (...),(...);` into objects keyed by column.
function rowsOf(table) {
	const start = dump.indexOf('INSERT INTO `' + table + '` VALUES');
	if (start < 0) return [];
	const cols = columnsOf(table);
	const rows = [];
	let i = dump.indexOf('VALUES', start) + 'VALUES'.length;
	let row = null;
	let tok = '';
	let quoted = false;
	for (; i < dump.length; i++) {
		const c = dump[i];
		if (row === null) {
			if (c === '(') row = [];
			else if (c === ';') break;
			continue;
		}
		if (c === "'") {
			// quoted string with MySQL backslash escapes
			for (i++; dump[i] !== "'"; i++) {
				if (dump[i] === '\\') {
					const e = dump[++i];
					tok += { n: '\n', r: '\r', t: '\t', 0: '\0' }[e] ?? e;
				} else tok += dump[i];
			}
			quoted = true;
		} else if (c === ',' || c === ')') {
			row.push(quoted ? tok : tok.trim() === 'NULL' ? null : Number(tok));
			tok = '';
			quoted = false;
			if (c === ')') {
				rows.push(Object.fromEntries(cols.map((k, j) => [k, row[j]])));
				row = null;
			}
		} else tok += c;
	}
	return rows;
}

// ---------------------------------------------------------------- SQL output

const lit = (v) => {
	if (v === null || v === undefined) return 'null';
	if (typeof v === 'boolean') return v ? 'true' : 'false';
	if (typeof v === 'number') return String(v);
	return "'" + String(v).replace(/'/g, "''") + "'";
};
const json = (s) => lit(JSON.stringify(JSON.parse(s))) + '::jsonb';
const bool = (n) => n === 1;
const fk = (n) => (n ? n : null); // EF wrote 0 for "no category"

function insert(table, objs) {
	if (!objs.length) return '';
	const cols = Object.keys(objs[0]);
	const values = objs.map((o) => '  (' + cols.map((c) => o[c]).join(', ') + ')').join(',\n');
	return (
		`insert into public.${table} (${cols.join(', ')}) values\n${values};\n` +
		`select setval(pg_get_serial_sequence('public.${table}', 'id'), (select max(id) from public.${table}));\n\n`
	);
}

const only = (ids) => (r) => ids.includes(r.Id);

// Old wwwroot paths -> object paths in the `images` bucket.
const images = [];
function image(oldPath, folder) {
	if (!oldPath) return 'null';
	const objectPath = `${folder}/${path.basename(oldPath)}`;
	images.push({ from: path.join(wwwroot, oldPath), to: objectPath });
	return lit(objectPath);
}

// Real content rows; everything else in the dump is test data.
const categories = rowsOf('Categories').filter(only([11, 12]));
const funFacts = rowsOf('FunFact').filter((r) => r.Id !== 13); // 13 duplicates 12
const memes = rowsOf('FeedbackMemes');
const articles = rowsOf('AssignmentIntroductionArticles').filter(only([6]));
const questions = rowsOf('AssignmentIntroductionQuestions').filter((r) => r.AssignmentIntroductionArticleId === 6);
const texts = rowsOf('AssignmentManipulativeText').filter(only([32]));
const motivations = rowsOf('ManipulativeMotivations').filter((r) => r.ManipulativeTextId === 32);
const comments = rowsOf('ManipulativeComments').filter((r) => r.ManipulativeTextId === 32);
const biases = rowsOf('AssignmentCognitiveBiases').filter((r) => r.CategoryId === 11);
const quiz = rowsOf('AssignmentQuizQuestions').filter((r) => r.CategoryId === 11);
const lens = rowsOf('AssignmentGoogleLens').filter((r) => r.CategoryId === 11);
const lensAnswers = rowsOf('AssignmentGoogleLensSources').filter(
	(r) => !['hej', 'string'].includes(r.AllowedDescription)
);

let seed = '-- Generated by scripts/migrate-from-mysql.mjs from the production MySQL dump.\n\n';
seed += insert(
	'categories',
	categories.map((r) => ({
		id: r.Id,
		name: lit(r.Name),
		description: lit(r.Description),
		visible: lit(bool(r.Visible)),
		duration: r.Duration,
		img_path: image(r.ImgSrc, 'categories')
	}))
);
seed += insert(
	'fun_facts',
	funFacts.map((r) => ({ id: r.Id, category_id: r.CategoriesId, title: lit(r.Title), text: lit(r.Text) }))
);
seed += insert(
	'feedback_memes',
	memes.map((r) => ({
		id: r.Id,
		category_id: r.CategoriesId,
		description: lit(r.Desctiption === 'string' ? '' : r.Desctiption),
		img_path: image(r.ImgSrc, 'feedback-memes')
	}))
);
seed += insert(
	'intro_articles',
	articles.map((r) => ({
		id: r.Id,
		category_id: lit(fk(r.CategoryId)),
		title: lit(r.Title),
		content: lit(r.Content),
		instructions: lit(r.Instructions),
		img_path: image(r.ImgSrc, 'intro-articles'),
		user_feedback: lit(r.UserFeedback),
		visible: lit(bool(r.Visible))
	}))
);
seed += insert(
	'intro_questions',
	questions.map((r) => ({
		id: r.Id,
		article_id: r.AssignmentIntroductionArticleId,
		term: lit(r.Term),
		description: lit(r.Description)
	}))
);
seed += insert(
	'manipulative_texts',
	texts.map((r) => ({
		id: r.Id,
		category_id: lit(fk(r.CategoryId)),
		intro_article_id: lit(r.AssignmentIntroductionArticleId),
		instructions: lit(r.Instructions),
		manipulative_parts: json(r.ManipulativeParts),
		user_feedback: lit(r.UserFeedback),
		visible: lit(bool(r.Visible))
	}))
);
seed += insert(
	'manipulative_motivations',
	motivations.map((r) => ({
		id: r.Id,
		text_id: r.ManipulativeTextId,
		motivation: lit(r.Motivation),
		definition: lit(r.Definition)
	}))
);
seed += insert(
	'manipulative_comments',
	comments.map((r) => ({
		id: r.Id,
		text_id: r.ManipulativeTextId,
		motivation_id: r.ManipulativeMotivationId,
		comment: lit(r.Comment),
		username: lit(r.Username),
		explanation: lit(r.ManipulativeExplanation)
	}))
);
seed += insert(
	'cognitive_biases',
	biases.map((r) => ({
		id: r.Id,
		category_id: r.CategoryId,
		cognitive_bias: lit(r.CognitiveBias),
		definition: lit(r.Definition),
		example: lit(r.Example),
		visible: lit(bool(r.Visible))
	}))
);
seed += insert(
	'quiz_questions',
	quiz.map((r) => ({
		id: r.Id,
		category_id: r.CategoryId,
		question: lit(r.Question),
		answers: json(r.Answer),
		visible: lit(bool(r.Visible))
	}))
);
seed += insert(
	'lens_photos',
	lens.map((r) => ({
		id: r.Id,
		category_id: r.CategoryId,
		img_path: image(r.ImgSrc, 'google-lens'),
		correct_answer: lit(r.CorrectAnswer)
	}))
);
seed += insert(
	'lens_accepted_answers',
	lensAnswers.map((r) => ({ id: r.Id, photo_id: r.AssignmentGoogleLensId, answer: lit(r.AllowedDescription) }))
);

const feedback = rowsOf('Feedbacks').map((r) => ({
	id: r.Id,
	type_of_user: lit(r.TypeOfUser),
	name: lit(r.Name),
	age: lit(r.Age),
	email: lit(r.Email),
	gender: lit(r.Gender),
	newsletter_approved: lit(r.NewsletterApproved === null ? null : bool(r.NewsletterApproved)),
	stars: lit(r.Stars),
	feedback_further: lit(r.FeedbackFurther),
	created_at: r.Date ? lit(r.Date + '+00') : 'now()'
}));

fs.writeFileSync('supabase/seed.sql', seed);
fs.mkdirSync('scripts/out', { recursive: true });
fs.writeFileSync(
	'scripts/out/feedback.sql',
	'-- Player feedback (personal data). Do not commit.\n\n' + insert('feedback', feedback)
);

console.log(
	`seed.sql: ${categories.length} categories, ${funFacts.length} fun facts, ${memes.length} memes, ` +
		`${articles.length} articles, ${questions.length} intro questions, ${texts.length} texts, ` +
		`${motivations.length} motivations, ${comments.length} comments, ${biases.length} biases, ` +
		`${quiz.length} quiz questions, ${lens.length} lens photos, ${lensAnswers.length} lens answers`
);
console.log(`feedback.sql: ${feedback.length} rows`);

const missing = images.filter((i) => !fs.existsSync(i.from));
console.log(`images: ${images.length} referenced, ${missing.length} missing`);
for (const m of missing) console.log('  missing:', m.from);

// ---------------------------------------------------------------- image upload

if (upload) {
	const { createClient } = await import('@supabase/supabase-js');
	const { SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY } = process.env;
	if (!SUPABASE_URL || !SUPABASE_SERVICE_ROLE_KEY) {
		console.error('--upload needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY');
		process.exit(1);
	}
	const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY);
	const contentTypes = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' };
	for (const img of images.filter((i) => fs.existsSync(i.from))) {
		const { error } = await supabase.storage.from('images').upload(img.to, fs.readFileSync(img.from), {
			contentType: contentTypes[path.extname(img.from).toLowerCase()],
			upsert: true
		});
		console.log(error ? `  FAILED ${img.to}: ${error.message}` : `  uploaded ${img.to}`);
	}
}
