-- Klamarium schema (replaces the .NET / MySQL backend).
-- Players are anonymous: they can read game content and submit feedback.
-- Staff (app_metadata.role = 'admin' | 'editor') can edit content and read feedback.

-- ---------------------------------------------------------------- helpers

create or replace function public.is_editor()
returns boolean
language sql
stable
as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') in ('admin', 'editor');
$$;

-- ---------------------------------------------------------------- tables

create table public.categories (
  id          int generated by default as identity primary key,
  name        varchar(70)  not null,
  description varchar(400) not null default '',
  visible     boolean      not null default false,
  duration    int          not null default 0,
  img_path    text
);

create table public.fun_facts (
  id          int generated by default as identity primary key,
  category_id int  not null references public.categories (id) on delete cascade,
  title       text not null,
  text        text not null
);

create table public.feedback_memes (
  id          int generated by default as identity primary key,
  category_id int  not null references public.categories (id) on delete cascade,
  description text not null default '',
  img_path    text
);

create table public.intro_articles (
  id            int generated by default as identity primary key,
  category_id   int references public.categories (id) on delete set null,
  title         varchar(70) not null,
  content       text        not null,
  instructions  text        not null default '',
  img_path      text,
  user_feedback text,
  visible       boolean     not null default false
);

create table public.intro_questions (
  id          int generated by default as identity primary key,
  article_id  int  not null references public.intro_articles (id) on delete cascade,
  term        text not null,
  description text not null
);

create table public.manipulative_texts (
  id                 int generated by default as identity primary key,
  category_id        int references public.categories (id) on delete set null,
  intro_article_id   int references public.intro_articles (id) on delete set null,
  instructions       text    not null,
  manipulative_parts jsonb   not null default '[]'::jsonb,
  user_feedback      text,
  visible            boolean not null default false
);

create table public.manipulative_motivations (
  id         int generated by default as identity primary key,
  text_id    int  not null references public.manipulative_texts (id) on delete cascade,
  motivation text not null,
  definition text not null
);

create table public.manipulative_comments (
  id            int generated by default as identity primary key,
  text_id       int  not null references public.manipulative_texts (id) on delete cascade,
  motivation_id int  not null references public.manipulative_motivations (id) on delete cascade,
  comment       text not null,
  username      text not null,
  explanation   text
);

create table public.cognitive_biases (
  id             int generated by default as identity primary key,
  category_id    int     not null references public.categories (id) on delete cascade,
  cognitive_bias text    not null,
  definition     text    not null,
  example        text    not null,
  visible        boolean not null default false
);

create table public.quiz_questions (
  id          int generated by default as identity primary key,
  category_id int     not null references public.categories (id) on delete cascade,
  question    text    not null,
  answers     jsonb   not null default '[]'::jsonb, -- [{ "answer": text, "correct": bool }]
  visible     boolean not null default false
);

create table public.lens_photos (
  id             int generated by default as identity primary key,
  category_id    int  not null references public.categories (id) on delete cascade,
  img_path       text not null,
  correct_answer text not null default '' -- shown to the player after 3 failed attempts
);

-- Accepted answers are never readable by players; use check_lens_answer().
create table public.lens_accepted_answers (
  id       int generated by default as identity primary key,
  photo_id int  not null references public.lens_photos (id) on delete cascade,
  answer   text not null
);

-- Player questionnaire from the end of the game. Contains personal data.
create table public.feedback (
  id                  int generated by default as identity primary key,
  type_of_user        text,
  name                text,
  age                 int,
  email               text,
  gender              text,
  newsletter_approved boolean,
  stars               int,
  feedback_further    text,
  created_at          timestamptz not null default now()
);

create index on public.fun_facts (category_id);
create index on public.feedback_memes (category_id);
create index on public.intro_questions (article_id);
create index on public.manipulative_motivations (text_id);
create index on public.manipulative_comments (text_id);
create index on public.cognitive_biases (category_id);
create index on public.quiz_questions (category_id);
create index on public.lens_photos (category_id);
create index on public.lens_accepted_answers (photo_id);

-- ---------------------------------------------------------------- RLS

-- Game content: anyone reads, staff writes.
do $$
declare
  t text;
begin
  foreach t in array array[
    'categories', 'fun_facts', 'feedback_memes', 'intro_articles', 'intro_questions',
    'manipulative_texts', 'manipulative_motivations', 'manipulative_comments',
    'cognitive_biases', 'quiz_questions', 'lens_photos'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "public read" on public.%I for select using (true)', t);
    execute format(
      'create policy "staff write" on public.%I for all to authenticated using (public.is_editor()) with check (public.is_editor())',
      t
    );
  end loop;
end
$$;

alter table public.lens_accepted_answers enable row level security;
create policy "staff only" on public.lens_accepted_answers
  for all to authenticated using (public.is_editor()) with check (public.is_editor());

alter table public.feedback enable row level security;
create policy "anyone submits" on public.feedback
  for insert to anon, authenticated with check (true);
create policy "staff reads" on public.feedback
  for select to authenticated using (public.is_editor());
create policy "staff deletes" on public.feedback
  for delete to authenticated using (public.is_editor());

-- ---------------------------------------------------------------- RPC

-- Case-insensitive match of a player's Google Lens answer against the accepted answers.
create or replace function public.check_lens_answer(photo_id int, answer text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.lens_accepted_answers a
    where a.photo_id = check_lens_answer.photo_id
      and lower(trim(a.answer)) = lower(trim(check_lens_answer.answer))
  );
$$;

grant execute on function public.check_lens_answer(int, text) to anon, authenticated;

-- ---------------------------------------------------------------- storage

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('images', 'images', true, 10485760, array['image/png', 'image/jpeg', 'image/webp', 'image/gif'])
on conflict (id) do nothing;

-- The bucket is public for downloads; the Storage API still needs a select policy to remove or replace objects.
create policy "staff lists images" on storage.objects
  for select to authenticated using (bucket_id = 'images' and public.is_editor());
create policy "staff uploads images" on storage.objects
  for insert to authenticated with check (bucket_id = 'images' and public.is_editor());
create policy "staff updates images" on storage.objects
  for update to authenticated using (bucket_id = 'images' and public.is_editor());
create policy "staff deletes images" on storage.objects
  for delete to authenticated using (bucket_id = 'images' and public.is_editor());
